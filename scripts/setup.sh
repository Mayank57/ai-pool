#!/usr/bin/env bash
# One-time setup: generates secrets (.env) and the routing-engine (CLIProxyAPI) config.
#
#   scripts/setup.sh                                   # this computer, http://localhost:8320
#   scripts/setup.sh --mode docker --url https://ai.acme.com   # a server
#
# Re-running keeps existing secrets. --force regenerates proxy/config.yaml.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MODE="local"
URL=""
FORCE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --mode) MODE="$2"; shift 2 ;;
    --url) URL="$2"; shift 2 ;;
    --force) FORCE=1; shift ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done
[[ "$MODE" == "local" || "$MODE" == "docker" ]] || { echo "--mode must be local or docker" >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }
rand() { openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }

ENV_FILE="$ROOT/.env"
touch "$ENV_FILE"; chmod 600 "$ENV_FILE"
# shellcheck disable=SC1090
set -a; source "$ENV_FILE"; set +a
add() { grep -q "^$1=" "$ENV_FILE" || { printf '%s=%s\n' "$1" "$2" >> "$ENV_FILE"; export "$1=$2"; echo "• Added $1 to .env"; }; }

grep -q '^# AI Pool' "$ENV_FILE" || printf '# AI Pool secrets (generated by scripts/setup.sh). Keep this file private.\n' >> "$ENV_FILE"
add MANAGEMENT_KEY "$(rand 40)"
add APP_SECRET "$(rand 48)"
add APP_PUBLIC_URL "${URL:-http://localhost:8320}"
add PROXY_URL "http://127.0.0.1:8317"
add AIPOOL_MODE "$MODE"

PROXY_DIR="$ROOT/proxy"
CONFIG="$PROXY_DIR/config.yaml"
mkdir -p "$PROXY_DIR/auths" "$ROOT/data"
if [[ -f "$CONFIG" && $FORCE -eq 0 ]]; then
  echo "• Keeping existing proxy/config.yaml (use --force to regenerate)"
else
  if [[ "$MODE" == "local" ]]; then BIND="127.0.0.1"; AUTH_DIR="$PROXY_DIR/auths"; else BIND=""; AUTH_DIR="/root/.cli-proxy-api"; fi
  umask 077
  cat > "$CONFIG" <<EOF
# Routing engine (CLIProxyAPI) config generated by AI Pool. Reference: CLIProxyAPI/config.example.yaml
# AI Pool manages client keys, upstream API keys and routing prefixes through the management API.
config-version: 8
server:
  host: "$BIND"
  port: 8317
management:
  allow-remote: false
  secret-key: "$MANAGEMENT_KEY"
  disable-control-panel: true
access:
  api-keys: []
oauth:
  auth-dir: "$AUTH_DIR"
routing:
  strategy: "round-robin"
  # Workspace isolation: requests must name a routing prefix (added by AI Pool's gateway).
  force-model-prefix: true
  session-affinity: true
observability:
  logs:
    logging-to-file: true
    logs-max-total-size-mb: 200
  usage:
    usage-statistics-enabled: true
    redis-usage-queue-retention-seconds: 3600
EOF
  umask 022
  echo "• Wrote proxy/config.yaml"
fi

echo
echo "Setup complete ($MODE). AI Pool will be at: $APP_PUBLIC_URL"
if [[ "$MODE" == "local" ]]; then echo "Next: scripts/start-local.sh"; else echo "Next: docker compose -f deploy/docker-compose.yml --env-file .env up -d"; fi
